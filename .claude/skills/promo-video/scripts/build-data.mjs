// Gathers everything a film needs to know into <film>/data/film-data.js (window.FILM_DATA), so the page needs no
// fetches: the voiceover lines with absolute word times, the captured screens' control boxes, the music's beat grid,
// and the sizes of the screen captures and crops.
//   node tools/build-data.mjs [--film=shorts/eat]
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { loadSharp, filmRoot, filmFile, film } from "./paths.mjs";

const sharp = loadSharp();
const { lines } = await import(pathToFileURL(filmFile("voiceover-lines.mjs")).href);
const vo = lines.map((line, i) => {
  const n = String(i + 1).padStart(2, "0");
  if (!line.text) return { n, at: line.at, text: "", file: null, words: [], end: line.at }; // a wordless moment
  const j = JSON.parse(readFileSync(join(filmRoot, "audio", "vo", `line-${n}.json`), "utf8"));
  return { n, at: line.at, text: line.text, file: `audio/vo/line-${n}.mp3`,
    words: j.words.map(w => ({ w: w.word, t: +(line.at + w.start).toFixed(3), e: +(line.at + w.end).toFixed(3) })),
    end: +(line.at + j.words.at(-1).end).toFixed(3) };
});
const shotsDir = join(filmRoot, "assets", "shots");
mkdirSync(shotsDir, { recursive: true });
let shots = {};
try { shots = JSON.parse(readFileSync(join(shotsDir, "shots.json"), "utf8")); } catch { /* no captures yet */ }
const beats = JSON.parse(readFileSync(join(filmRoot, "audio", "music", `${film.music}.beats.json`), "utf8"));
const images = {};
for (const f of readdirSync(shotsDir).filter(f => /\.png$/.test(f) && !f.startsWith("_"))) {
  const m = await sharp(join(shotsDir, f)).metadata();
  images[f.replace(/\.png$/, "")] = [m.width, m.height];
}
const data = { vo, shots, beatTimes: beats.beatTimes, images };
mkdirSync(join(filmRoot, "data"), { recursive: true });
writeFileSync(join(filmRoot, "data", "film-data.js"), `// Generated by tools/build-data.mjs. Do not edit.\nwindow.FILM_DATA = ${JSON.stringify(data)};\n`);
console.log("lines", vo.length, "shots", Object.keys(shots).length, "images", Object.keys(images).length, "beats", beats.beatTimes.length);
