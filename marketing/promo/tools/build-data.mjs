// Gathers everything the film needs to know into data/film-data.js (window.FILM_DATA), so the page needs no fetches:
// the voiceover lines with absolute word times, the captured screens' control boxes, the music's beat grid, and the
// sizes of the screen captures and crops.
//   node tools/build-data.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { lines } from "./voiceover-lines.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
import { loadSharp } from "./paths.mjs";
const sharp = loadSharp();

const vo = lines.map((line, i) => {
  const n = String(i + 1).padStart(2, "0");
  const j = JSON.parse(readFileSync(join(root, "audio", "vo", `line-${n}.json`), "utf8"));
  return { n, at: line.at, text: line.text, file: `audio/vo/line-${n}.mp3`,
    words: j.words.map(w => ({ w: w.word, t: +(line.at + w.start).toFixed(3), e: +(line.at + w.end).toFixed(3) })),
    end: +(line.at + j.words.at(-1).end).toFixed(3) };
});
const shots = JSON.parse(readFileSync(join(root, "assets", "shots", "shots.json"), "utf8"));
const beats = JSON.parse(readFileSync(join(root, "audio", "music", "take1.mp3.beats.json"), "utf8"));
const images = {};
for (const f of readdirSync(join(root, "assets", "shots")).filter(f => /^s\d.*\.png$/.test(f))) {
  const m = await sharp(join(root, "assets", "shots", f)).metadata();
  images[f.replace(/\.png$/, "")] = [m.width, m.height];
}
const data = { vo, shots, beatTimes: beats.beatTimes, images };
writeFileSync(join(root, "data", "film-data.js"), `// Generated by tools/build-data.mjs. Do not edit.\nwindow.FILM_DATA = ${JSON.stringify(data)};\n`);
console.log("lines", vo.length, "shots", Object.keys(shots).length, "images", Object.keys(images).length, "beats", beats.beatTimes.length);
